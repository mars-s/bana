#!/usr/bin/env python3
"""Generates the iPhone app's design tokens from web/src/tokens.css (the one source of truth).

    python3 scripts/gen-ios-tokens.py          # writes apps/bana-ios/Bana/Tokens.swift
    python3 scripts/gen-ios-tokens.py --check  # fails when Tokens.swift is out of date

Colours become dynamic SwiftUI colours (dark from `:root`, light from `:root[data-theme='light']`),
px sizes and unitless numbers become CGFloat, ms durations become seconds. Values the phone cannot
use (gradients, shadows, vh, calc) are skipped.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "web/src/tokens.css"
OUT = ROOT / "apps/bana-ios/Bana/Tokens.swift"


def blocks(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out = {}
    for sel, body in re.findall(r"(:root[^{]*)\{([^}]*)\}", css):
        key = "light" if "light" in sel else "dark"
        out[key] = dict(re.findall(r"--([\w-]+)\s*:\s*([^;]+);", body))
    return out


def resolve(v, table, other):
    for _ in range(8):
        m = re.fullmatch(r"var\(--([\w-]+)\)", v.strip())
        if not m:
            return v.strip()
        v = table.get(m.group(1), other.get(m.group(1), ""))
    return v.strip()


def color(v):
    v = v.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", v)
    if m:
        r, g, b = (int(m.group(1)[i : i + 2], 16) for i in (0, 2, 4))
        a = int(m.group(2), 16) / 255 if m.group(2) else 1.0
        return (r, g, b, a)
    m = re.fullmatch(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)", v)
    if m:
        return (int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4) or 1))
    return None


def camel(name):
    head, *rest = name.replace(".", "_").split("-")
    s = head + "".join(p[:1].upper() + p[1:] for p in rest)
    return ("t" + s) if s[:1].isdigit() else s


def ui(c):
    r, g, b, a = c
    return f"UIColor(red: {r / 255:.4f}, green: {g / 255:.4f}, blue: {b / 255:.4f}, alpha: {a:.4f})"


def generate():
    b = blocks(CSS.read_text())
    dark, light = b["dark"], b.get("light", {})
    colors, sizes, light_sizes, times = [], [], [], []
    for name in list(dark) + [n for n in light if n not in dark]:
        dv = resolve(dark.get(name, light.get(name, "")), dark, light)
        lv = resolve(light.get(name, dark.get(name, "")), {**dark, **light}, dark)
        dc, lc = color(dv), color(lv)
        if dc and lc:
            colors.append((camel(name), dc, lc))
            continue
        m = re.fullmatch(r"(-?[\d.]+)(px)?", dv)
        if m:
            sizes.append((camel(name), float(m.group(1))))
            ml = re.fullmatch(r"(-?[\d.]+)(px)?", lv)
            if ml and float(ml.group(1)) != float(m.group(1)):
                light_sizes.append((camel(name), float(ml.group(1))))
            continue
        m = re.match(r"([\d.]+)ms\b", dv)
        if m:
            times.append((camel(name), float(m.group(1)) / 1000))
    lines = [
        "// Generated by scripts/gen-ios-tokens.py from web/src/tokens.css. Do not edit by hand.",
        "// Colours are dynamic (dark and light theme); sizes are points; times are seconds.",
        "import SwiftUI",
        "import UIKit",
        "",
        "enum T {",
        "    private static func dyn(_ dark: UIColor, _ light: UIColor) -> Color {",
        "        Color(UIColor { $0.userInterfaceStyle == .dark ? dark : light })",
        "    }",
        "",
    ]
    for n, dc, lc in colors:
        lines.append(f"    static let {n} = dyn({ui(dc)}, {ui(lc)})")
    lines.append("")
    for n, v in sizes:
        lines.append(f"    static let {n}: CGFloat = {v:g}")
    lines.append("")
    lines.append("    /// Numbers the light theme sets differently (font weights).")
    for n, v in light_sizes:
        lines.append(f"    static let {n}Light: CGFloat = {v:g}")
    lines.append("")
    for n, v in times:
        lines.append(f"    static let {n}: Double = {v:g}")
    tags = sorted({re.match(r"tag-(\w+)-fg$", n).group(1) for n in dark if re.match(r"tag-(\w+)-fg$", n)})
    lines.append("")
    lines.append("    /// Supertag colours by name: fg (text, dot, ring), t1 (chip fill), t2 (bullet halo).")
    lines.append("    static let tags: [String: (fg: Color, t1: Color, t2: Color)] = [")
    for t in tags:
        c = camel(f"tag-{t}")
        lines.append(f'        "{t}": ({c}Fg, {c}T1, {c}T2),')
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date: run python3 scripts/gen-ios-tokens.py")
        sys.exit(0)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
